// Generates src/components/icon-paths.js: inline SVG paths for every Material
// Symbols icon the site uses (Outlined, weight 400). Self-hosted icons mean no
// request to Google's font servers and no flash of blank icons.
//   npm run build:icons   (re-run after using a new icon name)
import { readdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const require = createRequire(import.meta.url);
const iconDir = path.join(path.dirname(require.resolve('@material-symbols/svg-400/package.json')), 'outlined');
export const ICON_PATTERN = /(?:<Icon[^>]*\bname=|\bicon\s*[:=]\s*|\bIcon name=\{[^}?]*\?\s*)["']([a-z0-9_]+)["']/g;

async function walk(dir) {
  const out = [];
  for (const e of await readdir(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) out.push(...(await walk(p)));
    else if (/\.(jsx?)$/.test(e.name) && e.name !== 'icon-paths.js') out.push(p);
  }
  return out;
}

export async function usedIcons() {
  const names = new Set();
  for (const f of await walk(path.join(root, 'src'))) {
    const text = await readFile(f, 'utf8');
    for (const m of text.matchAll(ICON_PATTERN)) {
      names.add(m[1]);
      if (m[2]) names.add(m[2]);
    }
  }
  return [...names].sort();
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const names = await usedIcons();
  const entries = [];
  for (const name of names) {
    const svg = await readFile(path.join(iconDir, `${name}.svg`), 'utf8').catch(() => {
      throw new Error(`Unknown Material Symbols icon "${name}"`);
    });
    const d = [...svg.matchAll(/<path d="([^"]+)"/g)].map((m) => m[1]).join(' ');
    entries.push(`  ${JSON.stringify(name)}: ${JSON.stringify(d)},`);
  }
  const out = `// Generated by scripts/build-icons.mjs from @material-symbols/svg-400 (Apache-2.0). Do not edit.\n// viewBox for all paths: "0 -960 960 960"\nexport const iconPaths = {\n${entries.join('\n')}\n};\n`;
  await writeFile(path.join(root, 'src/components/icon-paths.js'), out);
  console.log(`Wrote ${names.length} icons to src/components/icon-paths.js`);
}
